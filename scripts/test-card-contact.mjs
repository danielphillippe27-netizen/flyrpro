import {build} from 'esbuild';
import {mkdtemp, mkdir} from 'node:fs/promises';
import {join} from 'node:path';
import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
await mkdir('node_modules/.cache',{recursive:true});
const dir=await mkdtemp(join(process.cwd(),'node_modules/.cache/card-contact-'));
await build({entryPoints:['lib/cards/contact.ts','lib/cards/contracts.ts'],outdir:dir,bundle:true,platform:'node',format:'cjs',packages:'external',logLevel:'silent'});
const require=createRequire(import.meta.url);const {contactDownload}=require(join(dir,'contact.js'));const {cardContentSchema,vcard}=require(join(dir,'contracts.js'));const sharp=require('sharp');
process.env.SUPABASE_URL='https://fixture.supabase.co';
const photo=await sharp({create:{width:30,height:30,channels:3,background:'#ff0000'}}).webp().toBuffer();
let requests=0;globalThis.fetch=async()=>{requests++;return new Response(photo)};
const card=cardContentSchema.parse({name:'Daniel Phillippe',photo:process.env.SUPABASE_URL+'/storage/v1/object/public/business-card-images/photo.webp',phone:'2895550123'});
const result=await contactDownload(card);const unfolded=result.replace(/\r\n /g,'');
assert(unfolded.includes('N:Phillippe;Daniel;;;\r\n'));assert(unfolded.includes('FN:Daniel Phillippe\r\n'));
const image=unfolded.match(/PHOTO;ENCODING=b;TYPE=JPEG:([^\r]+)/)[1];assert.equal((await sharp(Buffer.from(image,'base64')).metadata()).format,'jpeg');
for(const line of result.split('\r\n'))assert(Buffer.byteLength(line)<=75);
const unicode=vcard({...card,name:'É'.repeat(90)},image);assert(unicode.replace(/\r\n /g,'').includes('FN:'+'É'.repeat(90)));
for(const line of unicode.split('\r\n'))assert(Buffer.byteLength(line)<=75);
await contactDownload({...card,photo:'https://127.0.0.1/private'});assert.equal(requests,1,'External URLs must not be fetched');
globalThis.fetch=async()=>new Response('missing',{status:404});assert((await contactDownload(card)).includes('N:Phillippe;Daniel;;;'));
assert(vcard({...card,name:'Prince',photo:''}).includes('N:;Prince;;;'));
console.log('Contact export passed: first/last name, embedded JPEG, UTF-8 folding, single name, external URL isolation, photo failure fallback');
