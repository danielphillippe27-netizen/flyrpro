import assert from 'node:assert/strict';
import { gmailMime, seal, unseal, gmailConfig } from '../gmail';
process.env.GMAIL_OAUTH_CLIENT_ID = 'test-client';
process.env.GMAIL_OAUTH_CLIENT_SECRET = 'test-secret';
process.env.GMAIL_OAUTH_REDIRECT_URI = 'https://example.com/callback';
process.env.OUTREACH_ENCRYPTION_KEY = 'test-only-encryption-key-32-characters';
const value = { token: 'test-refresh-token' };
const encrypted = seal(value);
assert(!encrypted.includes(value.token));
assert.deepEqual(unseal(encrypted), value);
const corrupted = Buffer.from(encrypted, 'base64url'); corrupted[30] ^= 1;
assert.throws(() => unseal(corrupted.toString('base64url')));
const mime = Buffer.from(gmailMime('me@example.com', 'home@example.com', 'Hello 🏡'.repeat(20), 'Line one\nLine two'), 'base64url').toString();
assert(mime.includes('To: home@example.com\r\n'));
assert(mime.split('\r\n').filter(line => line.startsWith('Subject:') || line.startsWith(' =?')).every(line => line.length < 80));
assert.equal(Buffer.from(mime.split('\r\n\r\n')[1].replace(/\r\n/g, ''), 'base64').toString(), 'Line one\nLine two');
assert.throws(() => gmailMime('me@example.com\r\nBcc: x@example.com', 'home@example.com', 'Hello', 'Body'));
delete process.env.OUTREACH_ENCRYPTION_KEY;
assert.throws(() => gmailConfig());
console.log('Gmail encryption, tamper rejection, MIME encoding and missing-config checks passed.');
