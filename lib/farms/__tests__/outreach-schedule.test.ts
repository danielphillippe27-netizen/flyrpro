import assert from 'node:assert/strict';
import { defaultOutreachSettings, forecastOutreach, outreachDate, validateOutreachSettings } from '../outreach-schedule';
import { buildAnnualCoveragePlan, validateAnnualCoverageSettings } from '../annual-coverage';
import { buildFarmDoorPlan } from '../door-plan';
const settings = defaultOutreachSettings();
const result = forecastOutreach(13793, '2026-10-27', 52, settings);
assert.equal(result.doorDays, 276);
assert.equal(result.daysNeeded, 276);
assert.equal(result.availableDays, 312);
assert.equal(result.spareDays, 36);
assert(result.fits);
assert(result.finishDate! <= outreachDate('2026-10-27', 363));
const holidays = ['2026-12-25', '2026-12-26', '2026-12-27'];
const off = forecastOutreach(13793, '2026-10-27', 52, { ...settings, holidays });
assert.equal(off.availableDays, 310, 'Sunday already excluded, no double counting');
assert.equal(off.holidaysExcluded, 2);
assert(off.finishDate! > result.finishDate!);
const separated = { ...settings, holidays: [], holidaysEnabled: true, holidayCountry: 'CA', holidayRegion: 'ON', publicHolidays: ['2026-12-25'], extraDaysOff: ['2026-12-24'] };
assert.deepEqual(validateOutreachSettings(separated).holidays, ['2026-12-24', '2026-12-25']);
assert.deepEqual(validateOutreachSettings({ ...separated, holidaysEnabled: false }).holidays, ['2026-12-24']);
assert.deepEqual(validateOutreachSettings({ ...settings, holidays: ['2026-12-25'] }).holidays, ['2026-12-25'], 'legacy plans retain their dates');
assert.equal(forecastOutreach(100, '2026-12-24', 1, separated).finishDate, '2026-12-28');
const short = forecastOutreach(20000, '2026-10-27', 52, settings);
assert.equal(short.fits, false);
assert.equal(short.minimumDoorsPerDay, 65);
assert(short.finishDate! > outreachDate('2026-10-27', 363));
const calls = forecastOutreach(1000, '2026-10-27', 52, { ...settings, doorPasses: 2, callPasses: 3, callsPerDay: 25 });
assert.equal(calls.doorAttempts, 2000);
assert.equal(calls.callAttempts, 3000);
assert.equal(calls.doorDays, 40);
assert.equal(calls.callDays, 120);
assert.equal(calls.daysNeeded, 120);
assert.equal(calls.doorRoundDates.length, 2);
assert.equal(calls.callRoundDates.length, 3);
assert.equal(forecastOutreach(0, '2026-10-27', 52, settings).finishDate, null);
assert.throws(() => validateOutreachSettings({ ...settings, workingDays: [] }));
assert.throws(() => validateOutreachSettings({ ...settings, doorPasses: 0, callPasses: 0 }));
assert.throws(() => validateOutreachSettings({ ...settings, holidays: ['2027-02-30'] }));
assert.throws(() => validateOutreachSettings({ ...settings, doorsPerDay: 0 }));
assert.equal(forecastOutreach(1, '2028-02-29', 1, settings).finishDate, '2028-02-29');
const homes = Array.from({ length: 301 }, (_, i) => ({ id: String(i), street_name: 'Main', house_number: String(i) }));
const annual = { startDate: '2026-12-21', homesPerWeek: 300, weeksInPlan: 2, weeksOff: [], outreach: { ...settings, holidays: ['2026-12-25'] } };
assert.equal(validateAnnualCoverageSettings(annual).outreach?.doorsPerDay, 50);
const plan = buildAnnualCoveragePlan(homes, annual);
assert.equal(plan.weeks[0].addressIds.length, 250, '5 working days after Friday holiday');
assert.equal(plan.weeks[1].addressIds.length, 51);
assert.equal(plan.finishDate, '2026-12-29', 'Exact working-day finish, not end-of-week estimate');
const partial = buildAnnualCoveragePlan(homes, { ...annual, weeksInPlan: 1, outreach: { ...settings, doorsPerDay: 10 } });
assert(partial.unassignedAddressIds.length > 0);
assert(partial.finishDate! > partial.weeks[0].endDate, 'slow plans retain a projected completion beyond their first year');
assert.equal(partial.weeks.flatMap(week => week.addressIds).length + partial.unassignedAddressIds.length, homes.length);
assert.equal(forecastOutreach(100, '2026-12-21', 2, { ...settings, doorPasses: 0, callPasses: 1, callsPerDay: 25 }).daysNeeded, 4);
const daily = buildFarmDoorPlan(homes, annual.startDate, 50, { workingDays: settings.workingDays, holidays: annual.outreach.holidays });
assert.equal(daily.days.length, 7);
assert.equal(daily.days.at(-1)!.date, plan.finishDate);
assert(!daily.days.some(day => day.date === '2026-12-25' || day.date === '2026-12-27'));
assert(daily.days.some(day => day.date === '2026-12-26'), 'Six-day schedule includes Saturday');
assert.equal(new Set(daily.days.flatMap(day => day.addressIds)).size, 301);
const repeated = buildFarmDoorPlan(homes, annual.startDate, 50, { workingDays: settings.workingDays, holidays: [], rounds: 2 });
assert.equal(repeated.days.flatMap(day => day.addressIds).length, 602);
assert.throws(() => buildFarmDoorPlan(homes, annual.startDate, 50, { workingDays: [], holidays: [] }));
console.log('PASS outreach forecasting: 50 × 6 days, holidays, repeated rounds, calling targets, shortfall, leap dates, exact daily allocation and saved settings.');
