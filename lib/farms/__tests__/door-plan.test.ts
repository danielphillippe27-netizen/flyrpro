import assert from 'node:assert/strict';
import { buildFarmDoorPlan } from '../door-plan';
const homes = Array.from({ length: 12003 }, (_, i) => ({ id: String(i), street_name: `Street ${Math.floor(i / 100)}`, house_number: String(i % 100), formatted: `Home ${i}` }));
const plan = buildFarmDoorPlan(homes, '2026-10-30', 100);
assert.equal(plan.days[0].date, '2026-10-30');
assert.equal(plan.days[1].date, '2026-11-02');
assert.equal(plan.days.length, 121);
assert.equal(plan.days.at(-1)?.addressIds.length, 3);
const ids = plan.days.flatMap(day => day.addressIds);
assert.equal(ids.length, homes.length);
assert.equal(new Set(ids).size, homes.length);
assert(plan.days.every(day => ![0, 6].includes(new Date(day.date).getUTCDay()) && day.addressIds.length <= 100));
assert.deepEqual(buildFarmDoorPlan([...homes].reverse(), '2026-10-30', 100), plan);
const excluded = buildFarmDoorPlan([...homes, homes[0], { id: 'dnc', last_outcome_status: 'do_not_knock' }], '2026-10-31', 1000);
assert.equal(excluded.excludedDoNotKnock, 1);
assert.equal(excluded.days[0].date, '2026-11-02');
assert.equal(excluded.days.flatMap(day => day.addressIds).length, homes.length);
assert.throws(() => buildFarmDoorPlan(homes, '2026-02-30', 100));
for (const capacity of [0, -1, 1.5, 1001, NaN, Infinity]) assert.throws(() => buildFarmDoorPlan(homes, '2026-10-27', capacity));
assert.equal(buildFarmDoorPlan([], '2026-10-27', 100).days.length, 0);
console.log('Farm door plan: full coverage, stable ordering, weekday dates, limits, and exclusions passed.');
