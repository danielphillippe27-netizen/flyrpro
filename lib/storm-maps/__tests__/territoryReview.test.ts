import assert from 'node:assert/strict';
import type { Polygon } from 'geojson';
import { reviewPolygonSchema, inspectionsWithin, latestInspectionRecords, overlapSquareMeters, type InspectionRecord } from '../intelligence/territory-review';
const square:Polygon={type:'Polygon',coordinates:[[[0,0],[0.1,0],[0.1,0.1],[0,0.1],[0,0]]]};
assert.ok(reviewPolygonSchema.safeParse(square).success);
assert.equal(reviewPolygonSchema.safeParse({type:'Polygon',coordinates:[[[0,0],[1,1],[0,1],[1,0],[0,0]]]}).success,false);
assert.equal(reviewPolygonSchema.safeParse({type:'Polygon',coordinates:[[[0,0],[0.1,0],[0.1,0.1],[0,0.1]]]}).success,false);
assert.equal(reviewPolygonSchema.safeParse({type:'Polygon',coordinates:[[[0,0],[10,0],[10,10],[0,10],[0,0]]]}).success,false);
assert.equal(reviewPolygonSchema.safeParse({type:'Polygon',coordinates:[[[179,0],[-179,0],[-179,1],[179,0]]]}).success,false);
const record=(id:string,lon:number,lat:number,label:string,outcome='pending',date='2026-10-01T00:00:00Z'):InspectionRecord=>({id,event_key:'storm',longitude:lon,latitude:lat,property_label:label,outcome,notes:'',observed_at:date});
const rows=[record('1',.02,.02,'Unit A'),record('2',.02,.02,'Unit A','follow_up','2026-10-02T00:00:00Z'),record('3',.02,.02,'Unit B','do_not_knock'),record('4',.2,.2,'Outside')];
assert.equal(latestInspectionRecords(rows).length,3);
assert.deepEqual(inspectionsWithin(rows,square).map(x=>x.id),['2','3']);
const hole:Polygon={type:'Polygon',coordinates:[...square.coordinates,[[.01,.01],[.01,.03],[.03,.03],[.03,.01],[.01,.01]]]};
assert.equal(inspectionsWithin(rows,hole).length,0);
assert.ok(overlapSquareMeters(square,square)>100_000_000);
const touching:Polygon={type:'Polygon',coordinates:[[[.1,0],[.2,0],[.2,.1],[.1,.1],[.1,0]]]};
assert.equal(overlapSquareMeters(square,touching),0);
const halfway:Polygon={type:'Polygon',coordinates:[[[.05,0],[.15,0],[.15,.1],[.05,.1],[.05,0]]]};
assert.ok(Math.abs(overlapSquareMeters(square,halfway)/overlapSquareMeters(square,square)-.5)<.00001);
assert.equal(overlapSquareMeters(hole,{type:'Polygon',coordinates:[hole.coordinates[1]]}),0);
console.log('Territory review: invalid boundaries, date-line rejection, holes, edge-only contact, area overlap, latest records and separate units passed');
